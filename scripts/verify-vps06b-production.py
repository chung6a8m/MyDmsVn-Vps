#!/usr/bin/env python3
"""Strict VPS-06B generated Mediator outermost build, lock, and published runtime gate.

Not a replacement for SQL/HTTPS, Windows net48, or frozen 57-route acceptance.
"""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
host = root / "src/MyDmsVn.Server.AspNetCoreHost"
app = root / "src/MyDmsVn.Server.Application"
infra = root / "src/MyDmsVn.Server.Infrastructure"
host_tests = root / "tests/MyDmsVn.Server.AspNetCoreHost.Tests"
parse = argparse.ArgumentParser()
parse.add_argument("--stage", choices=["source", "published"], required=True)
parse.add_argument("--publish-dir")
args = parse.parse_args()


def packages(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    assert data["version"] == 2
    return data["dependencies"]["net10.0"]


# Lock files are *generated by NuGet*, committed, and restored in locked mode.
for directory in (app, infra, host, host_tests):
    lock = directory / "packages.vps06b.lock.json"
    assert lock.is_file(), f"Missing net10 lock: {lock}"
    deps = packages(lock)
    assert "Mediator.Abstractions" in deps, f"Native abstractions missing from {lock}"
    assert "MediatR" not in deps and "MediatR.Contracts" not in deps, f"MediatR leaked into {lock}"
    assert deps["Mediator.Abstractions"]["resolved"] == "3.0.2"
    assert ("Mediator.SourceGenerator" in deps) == (directory == host), \
        f"Generator must exist only in outermost production Host: {lock}"

app_project = (app / "MyDmsVn.Server.Application.csproj").read_text(encoding="utf-8-sig")
host_project = (host / "MyDmsVn.Server.AspNetCoreHost.csproj").read_text(encoding="utf-8-sig")
assert 'PackageReference Include="Mediator.SourceGenerator"' in host_project
assert 'PackageReference Include="Mediator.SourceGenerator"' not in app_project
assert "<Vps06bMediator>true</Vps06bMediator>" in host_project
assert "VPS06B_MEDIATOR" in app_project or "Vps06bMediator" in app_project
assert "#if !VPS06B_MEDIATOR" in (app / "DependencyInjection.cs").read_text(encoding="utf-8-sig")

if args.stage == "source":
    generated = host / "obj/mediator-generated"
    cs = sorted(generated.rglob("*.cs"))
    assert len(cs) >= 4, f"Expected generated Mediator C# in {generated}; found {len(cs)}"
    combined = "\n".join(p.read_text(encoding="utf-8-sig") for p in cs)
    for symbol in (
        "GetFoundationStatusQuery", "CreateProductCommand",
        "PostSalesReceiptCommand", "PostGoodsReceiptCommand",
        "MutateSecurityAdministrationCommand",
        "ExceptionHandlingBehavior", "AuthorizationBehavior", "ValidationBehavior",
    ):
        assert symbol in combined, f"Generated source lacks production type {symbol}"
    print(f"VPS06B_SOURCE_GENERATED_PASS files={len(cs)}: production requests and pipeline emitted")
else:
    assert args.publish_dir, "--publish-dir is required for published stage"
    publish = Path(args.publish_dir)
    manifest = publish / "MyDmsVn.Server.AspNetCoreHost.deps.json"
    runtimeconfig = publish / "MyDmsVn.Server.AspNetCoreHost.runtimeconfig.json"
    assert manifest.is_file() and runtimeconfig.is_file(), "Published Host runtime manifests missing"
    graph = json.loads(manifest.read_text(encoding="utf-8"))
    libs = graph["libraries"]
    packages = {name.split("/", 1)[0] for name in libs}
    assert "Mediator.Abstractions" in packages, "Runtime Mediator.Abstractions missing"
    assert "MediatR" not in packages and "MediatR.Contracts" not in packages, "Legacy MediatR in actual published Host"
    assert not list(publish.glob("MediatR*.dll")), "Legacy MediatR binaries in publish directory"
    assert "Mediator.SourceGenerator" not in packages, "Analyzer leaked into runtime graph"
    runtime = runtimeconfig.read_text(encoding="utf-8")
    assert "10.0" in runtime, "Non-net10 published artifact"
    print(f"VPS06B_PUBLISHED_RUNTIME_PASS libraries={len(libs)}, generated Mediator present, MediatR=0")
